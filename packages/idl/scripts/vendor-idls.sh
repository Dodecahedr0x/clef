#!/usr/bin/env bash
# Vendors official Codama IDLs for native programs, pinned to a commit per repo.
# To update: bump a commit (git ls-remote https://github.com/solana-program/<repo> HEAD), re-run, commit the result.
set -euo pipefail
cd "$(dirname "$0")/../idls"
PINS="
system 15f18487535a4f248afc1bf700a1a8a14f305452
token c666f1dc61f38dd0a9c0fcdeaeac4778274f7116
token-2022 7a23d8c3042d59b54aa7150f9dd6b5b3bd0c5e1a
associated-token-account 06b93de62562a86eb0a5da8164a40fd06fbd4f74
compute-budget b68894cf2ca3664db1f9530061c63033a461ac33
memo eb5ca9ab0f4a77dc1e1f5d2af151a3ebcf7332d2
"
{
  echo "# Vendored IDL sources"
  echo
  echo "Generated by \`scripts/vendor-idls.sh\`. Do not edit by hand."
  echo
  echo "| File | Repo | Commit | sha256 |"
  echo "| --- | --- | --- | --- |"
} > SOURCES.md
while read -r repo sha; do
  [ -z "$repo" ] && continue
  curl -fsSL "https://raw.githubusercontent.com/solana-program/$repo/$sha/idl.json" -o "$repo.json"
  echo "| $repo.json | solana-program/$repo | $sha | $(shasum -a 256 "$repo.json" | cut -d' ' -f1) |" >> SOURCES.md
  echo "$repo -> $(node -e "const r=require('./$repo.json'); console.log(r.kind, r.program.name, r.program.publicKey)")"
done <<< "$PINS"
